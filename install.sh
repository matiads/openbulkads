#!/bin/sh
# OpenBulkAds one-command installer (VPS, server or PC).
#
#   curl -fsSL https://raw.githubusercontent.com/matiads/openbulkads/main/install.sh | sh
#
# It checks Docker, saves the all-in-one compose file in ~/openbulkads,
# generates strong secrets in .env (only when .env does not exist yet), starts
# the stack and waits until /api/ready answers. Re-running keeps your .env.
#
# Options (environment variables, all optional):
#   OPENBULKADS_DIR           install directory            (default ~/openbulkads)
#   OPENBULKADS_PORT          host port                    (default 3000)
#   OPENBULKADS_BIND          host address to publish on   (default 127.0.0.1)
#   OPENBULKADS_URL           public URL users type in the browser
#                             (default http://localhost:<port>)
#   OPENBULKADS_VERSION       image tag                    (default latest)
#   OPENBULKADS_IMAGE         full image reference (overrides VERSION)
#   OPENBULKADS_REF           git ref the compose file is downloaded from (default main)
#   OPENBULKADS_COMPOSE_FILE  use this local compose file instead of downloading
#   OPENBULKADS_SKIP_PULL=1   do not pull the image (local images)
#   OPENBULKADS_SKIP_START=1  only prepare the directory, .env and compose file
#
# Everything lives inside main() so a truncated download does nothing.
set -eu

REPO="matiads/openbulkads"
DEFAULT_IMAGE_NAME="ghcr.io/matiads/openbulkads"

say() { printf '%s\n' "$*"; }
fail() { printf 'Error: %s\n' "$*" >&2; exit 1; }

# Random hex string made of $1 random bytes.
random_hex() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$1"
  else
    head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

# Canonical base64 of exactly 32 random bytes (44 characters, one "=").
random_key() {
  if command -v openssl >/dev/null 2>&1; then
    key=$(openssl rand -base64 32)
  else
    key=$(head -c 32 /dev/urandom | base64 | tr -d '\n')
  fi
  case "$key" in
    *=) [ "${#key}" -eq 44 ] && { printf '%s' "$key"; return 0; } ;;
  esac
  fail "No pude generar una clave aleatoria válida."
}

check_docker() {
  command -v docker >/dev/null 2>&1 ||
    fail "No encontré Docker. Instalalo desde https://docs.docker.com/get-docker/ y volvé a correr este comando."
  docker compose version >/dev/null 2>&1 ||
    fail "Falta Docker Compose v2 (el comando 'docker compose'). Instalalo desde https://docs.docker.com/compose/install/ y volvé a correr este comando."
  docker info >/dev/null 2>&1 ||
    fail "No puedo hablar con Docker. Revisá que esté encendido y que tengas permiso: agregá tu usuario al grupo docker ('sudo usermod -aG docker \$USER'), cerrá sesión y volvé a entrar (o corré 'newgrp docker') y repetí este comando sin sudo. No corras el instalador con sudo: usaría la carpeta de root en vez de la tuya y se perderían las variables."
}

download() {
  if command -v curl >/dev/null 2>&1; then
    curl -fsSL "$1" -o "$2"
  elif command -v wget >/dev/null 2>&1; then
    wget -qO "$2" "$1"
  else
    fail "Necesito curl o wget para bajar el archivo de configuración."
  fi
}

# Value of KEY in the .env file $1 (empty when absent).
env_value() {
  sed -n "s/^$2=//p" "$1" | head -n 1
}

# Set KEY=VALUE in the .env file $1, keeping every other line untouched.
set_env_value() {
  (
    umask 077
    grep -v "^$2=" "$1" > "$1.tmp" || true
    printf '%s=%s\n' "$2" "$3" >> "$1.tmp"
    mv "$1.tmp" "$1"
  )
}

# Update one setting in .env (called as: name new old) and say what changed.
update_setting() {
  [ "$2" = "$3" ] && return 0
  set_env_value .env "$1" "$2"
  say "==> Actualicé $1 en $dir/.env: $3 → $2"
}

write_env() {
  # Generate first: a failure inside the heredoc would leave an empty secret.
  db_password=$(random_hex 24)
  auth_secret=$(random_hex 32)
  token_key=$(random_key)
  (
    umask 077
    cat > "$1" <<ENV
# Generated by install.sh. Keep this file private: it holds your secrets.
# Do not delete it: without it you lose access to your database and Meta tokens.
POSTGRES_PASSWORD=$db_password
BETTER_AUTH_SECRET=$auth_secret
TOKEN_ENCRYPTION_KEY=$token_key
BETTER_AUTH_URL=$2
OPENBULKADS_BIND=$3
OPENBULKADS_PORT=$4
OPENBULKADS_IMAGE=$5
ENV
  )
  chmod 600 "$1"
}

wait_ready() {
  ready_url="$1"
  i=0
  while [ "$i" -lt 60 ]; do
    if command -v curl >/dev/null 2>&1; then
      body=$(curl -fsS --max-time 3 "$ready_url" 2>/dev/null || true)
    elif command -v wget >/dev/null 2>&1; then
      body=$(wget -qO- -T 3 "$ready_url" 2>/dev/null || true)
    else
      body=$(docker compose exec -T app node -e "fetch('http://127.0.0.1:3000/api/ready').then(r=>r.text()).then(t=>console.log(t))" 2>/dev/null || true)
    fi
    case "$body" in
      *'"ready":true'*) return 0 ;;
    esac
    i=$((i + 1))
    sleep 2
  done
  return 1
}

main() {
  dir="${OPENBULKADS_DIR:-$HOME/openbulkads}"
  # Explicit options: empty means "not passed" (keep the .env value on re-runs).
  port="${OPENBULKADS_PORT:-}"
  bind="${OPENBULKADS_BIND:-}"
  url="${OPENBULKADS_URL:-}"
  ref="${OPENBULKADS_REF:-main}"
  image="${OPENBULKADS_IMAGE:-$DEFAULT_IMAGE_NAME:${OPENBULKADS_VERSION:-latest}}"

  if [ -n "$port" ]; then
    case "$port" in
      *[!0-9]*) fail "OPENBULKADS_PORT tiene que ser un número entre 1 y 65535 (recibí '$port')." ;;
    esac
    [ "$port" -ge 1 ] && [ "$port" -le 65535 ] ||
      fail "OPENBULKADS_PORT tiene que ser un número entre 1 y 65535 (recibí '$port')."
  fi
  if [ -n "$bind" ]; then
    case "$bind" in
      *[!0-9A-Za-z.:-]*) fail "OPENBULKADS_BIND no es una dirección válida (recibí '$bind')." ;;
    esac
  fi
  if [ -n "$url" ]; then
    case "$url" in
      http://?*|https://?*) ;;
      *) fail "OPENBULKADS_URL tiene que empezar con http:// o https:// y tener un nombre (recibí '$url')." ;;
    esac
    url="${url%/}"
  fi

  say "==> Instalando OpenBulkAds en $dir"
  [ "${OPENBULKADS_SKIP_START:-}" = "1" ] || check_docker

  # Resolve a local compose file before changing directory.
  local_compose="${OPENBULKADS_COMPOSE_FILE:-}"
  if [ -n "$local_compose" ]; then
    [ -f "$local_compose" ] || fail "No existe OPENBULKADS_COMPOSE_FILE ($local_compose)."
    local_compose="$(cd "$(dirname "$local_compose")" && pwd)/$(basename "$local_compose")"
  fi

  mkdir -p "$dir"
  cd "$dir"

  # The compose file is refreshed on every run so updates bring new settings.
  if [ -n "$local_compose" ]; then
    cp "$local_compose" compose.yaml
  else
    say "==> Bajando la configuración de Docker Compose"
    download "https://raw.githubusercontent.com/$REPO/$ref/deploy/quickstart/compose.yaml" compose.yaml.tmp ||
      fail "No pude bajar compose.yaml desde GitHub (ref '$ref'). Revisá tu conexión."
    mv compose.yaml.tmp compose.yaml
  fi

  # Secrets are generated once. An existing .env keeps its secrets forever;
  # only settings passed explicitly in this run are updated.
  if [ -f .env ]; then
    chmod 600 .env
    say "==> Ya existe $dir/.env: lo conservo (tus claves no cambian)."
    old_port=$(env_value .env OPENBULKADS_PORT); old_port="${old_port:-3000}"
    old_url=$(env_value .env BETTER_AUTH_URL)
    if [ -n "${OPENBULKADS_IMAGE:-}${OPENBULKADS_VERSION:-}" ]; then
      update_setting OPENBULKADS_IMAGE "$image" "$(env_value .env OPENBULKADS_IMAGE)"
    fi
    if [ -n "$port" ]; then
      update_setting OPENBULKADS_PORT "$port" "$old_port"
      # The default URL follows the port; a custom URL is never touched.
      if [ -z "$url" ] && [ "$port" != "$old_port" ] && [ "$old_url" = "http://localhost:$old_port" ]; then
        update_setting BETTER_AUTH_URL "http://localhost:$port" "$old_url"
      fi
    fi
    [ -z "$bind" ] || update_setting OPENBULKADS_BIND "$bind" "$(env_value .env OPENBULKADS_BIND)"
    [ -z "$url" ] || update_setting BETTER_AUTH_URL "$url" "$old_url"
    chmod 600 .env
    port=$(env_value .env OPENBULKADS_PORT); port="${port:-3000}"
    bind=$(env_value .env OPENBULKADS_BIND); bind="${bind:-127.0.0.1}"
    url=$(env_value .env BETTER_AUTH_URL)
  else
    port="${port:-3000}"
    bind="${bind:-127.0.0.1}"
    url="${url:-http://localhost:$port}"
    say "==> Generando claves seguras en $dir/.env"
    write_env .env "$url" "$bind" "$port" "$image"
  fi

  if [ "${OPENBULKADS_SKIP_START:-}" = "1" ]; then
    say "Listo: preparé $dir sin iniciar nada (OPENBULKADS_SKIP_START=1)."
    return 0
  fi

  if [ "${OPENBULKADS_SKIP_PULL:-}" != "1" ]; then
    say "==> Descargando la imagen (puede tardar unos minutos)"
    docker compose pull ||
      fail "No pude descargar la imagen. Puede ser que todavía no esté publicada (si instalás una versión nueva) o que no tengas conexión a internet. Revisá tu conexión y repetí el comando."
  fi
  say "==> Iniciando OpenBulkAds"
  docker compose up -d ||
    fail "No pude iniciar OpenBulkAds. Si el puerto $port ya está ocupado, repetí el comando con otro puerto (por ejemplo OPENBULKADS_PORT=3500). Para más detalle corré 'cd $dir && docker compose logs'."

  check_host="$bind"
  case "$bind" in 0.0.0.0|::|'[::]') check_host="127.0.0.1" ;; esac
  say "==> Esperando a que esté listo"
  if ! wait_ready "http://$check_host:$port/api/ready"; then
    say "No arrancó a tiempo. Últimos mensajes:" >&2
    docker compose logs --tail 40 app >&2 || true
    fail "OpenBulkAds no respondió en /api/ready. Mirá los mensajes de arriba o corré 'cd $dir && docker compose logs'."
  fi

  cat <<DONE

Listo, OpenBulkAds está funcionando.

  1) Abrí ahora: $url/setup
  2) Completá /setup YA: hasta que crees el primer administrador, cualquiera
     que llegue a esa dirección podría quedarse con tu instalación.

Comandos útiles (corrélos dentro de $dir):
  Ver logs:    docker compose logs -f
  Actualizar:  docker compose pull && docker compose up -d
  Detener:     docker compose down

Guía completa: https://github.com/$REPO/blob/main/docs/deploy.md
DONE
}

main "$@"
